export function seedCharacters() {
  const db = getDb();
  const count = db.prepare('SELECT COUNT(*) AS n FROM characters WHERE is_official = 1').get().n;
  if (count > 0) return 0;
  for (const character of OFFICIAL_CHARACTERS) createCharacter(character, null, { official: true });
  return OFFICIAL_CHARACTERS.length;
}
